export interface CatalogProduct {
  /** URL 슬러그 겸 상품 ID */
  id: string;
  name: string;
  /** 목록 카드 한 줄 설명 */
  tagline: string;
  /** 공급가액 (원, VAT 별도) */
  price: number;
  /** 수량 변경 가능 여부 — 월 유지보수처럼 개월 수를 고르는 상품에만 true */
  quantifiable: boolean;
  /** 수량 단위 라벨 */
  unit: string;
  /** 최대 주문 수량 */
  maxQuantity: number;
  /** 대상 고객 */
  target: string;
  /** 제공 범위 — 결제 전 고지 (전자상거래법상 재화의 내용) */
  includes: string[];
  /** 포함되지 않는 것 — 분쟁 방지 */
  excludes: string[];
  /** 제공 기간·시기 */
  delivery: string;
  /** 상세 설명 문단 */
  description: string;
  /** 결제 전 반드시 읽어야 할 유의사항 */
  notice: string[];
}

