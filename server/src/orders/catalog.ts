export const findProduct = (id: string) => PRODUCTS.find((p) => p.id === id) ?? null;

/** 공급가 → VAT 포함 최종 결제 금액 */
export const withVat = (supply: number) => supply + Math.floor(supply * VAT_RATE);

/** 상품 + 수량 → 결제 금액 (서버 계산 전용) */
export function calcAmount(product: CatalogProduct, quantity: number) {
  const supply = product.price * quantity;
  const vat = Math.floor(supply * VAT_RATE);
  return { supply, vat, total: supply + vat };
}
